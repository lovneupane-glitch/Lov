create table if not exists public.media_files (
  id bigint generated by default as identity primary key,
  title text not null,
  description text default '',
  category text not null check (category in ('Videos','Audio','Photos')),
  original_name text not null,
  storage_path text not null unique,
  public_url text not null,
  created_at timestamptz not null default now()
);

alter table public.media_files enable row level security;

-- Give the website roles permission to use the table; row-level policies below restrict what they can do.
grant select on public.media_files to anon, authenticated;
grant insert, delete on public.media_files to authenticated;

drop policy if exists "Public can view media list" on public.media_files;
create policy "Public can view media list"
on public.media_files for select to anon, authenticated using (true);

-- IMPORTANT: Replace this placeholder with your own admin user's UUID.
create or replace function public.is_gallery_admin()
returns boolean language sql stable security definer set search_path = ''
as $$
  select auth.uid() = 'PASTE-ADMIN-USER-UUID-HERE'::uuid;
$$;

revoke all on function public.is_gallery_admin() from public;
grant execute on function public.is_gallery_admin() to authenticated;

drop policy if exists "Admin can add media rows" on public.media_files;
create policy "Admin can add media rows"
on public.media_files for insert to authenticated
with check (public.is_gallery_admin());

drop policy if exists "Admin can delete media rows" on public.media_files;
create policy "Admin can delete media rows"
on public.media_files for delete to authenticated
using (public.is_gallery_admin());

-- Create a PUBLIC Storage bucket named exactly: media
-- Public visitors can read files, but only your admin can upload/delete.
drop policy if exists "Anyone can view media objects" on storage.objects;
create policy "Anyone can view media objects"
on storage.objects for select to anon, authenticated
using (bucket_id = 'media');

drop policy if exists "Admin can upload media objects" on storage.objects;
create policy "Admin can upload media objects"
on storage.objects for insert to authenticated
with check (bucket_id = 'media' and public.is_gallery_admin());

drop policy if exists "Admin can delete media objects" on storage.objects;
create policy "Admin can delete media objects"
on storage.objects for delete to authenticated
using (bucket_id = 'media' and public.is_gallery_admin());
